#!/usr/bin/env python3
"""Generate the SDK string tables from localization/strings.json.

Writes
  Sources/OpenWish/Resources/Localizable.xcstrings          (Swift, Bundle.module)
  android/openwish/src/main/res/values*/openwish_strings.xml (Android, R.string.openwish_*)

Run from the repository root:  python3 scripts/generate-localizations.py
Pass --check to fail (exit 1) when the generated files are out of date (CI).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "localization" / "strings.json"
XCSTRINGS = ROOT / "Sources" / "OpenWish" / "Resources" / "Localizable.xcstrings"
ANDROID_RES = ROOT / "android" / "openwish" / "src" / "main" / "res"

# Apple language code -> extra Apple codes that get the same text.
APPLE_ALIASES = {"pt-BR": ["pt"]}

# Apple language code -> Android resource qualifiers.
ANDROID_QUALIFIERS = {
    "en": ["values"],
    "ar": ["values-ar"],
    "ca": ["values-ca"],
    "de": ["values-de"],
    "es": ["values-es"],
    "fr": ["values-fr"],
    "hi": ["values-hi"],
    "id": ["values-in"],
    "it": ["values-it"],
    "ja": ["values-ja"],
    "ko": ["values-ko"],
    "nl": ["values-nl"],
    "pl": ["values-pl"],
    "pt-BR": ["values-pt", "values-pt-rBR"],
    "pt-PT": ["values-pt-rPT"],
    "ru": ["values-ru"],
    "th": ["values-th"],
    "tr": ["values-tr"],
    "vi": ["values-vi"],
    "zh-Hans": ["values-zh-rCN"],
    "zh-Hant": ["values-zh-rTW", "values-zh-rHK"],
    "zu": ["values-zu"],
}

PLACEHOLDER = re.compile(r"\{n\}")


def android_name(key: str) -> str:
    return "openwish_" + key.replace(".", "_")


def swift_text(text: str) -> str:
    return PLACEHOLDER.sub("%lld", text)


def android_text(text: str) -> str:
    text = escape(text)
    # Android string resources treat these characters specially.
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if text.startswith(("@", "?")):
        text = "\\" + text
    return PLACEHOLDER.sub("%1$d", text)


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    languages = data["languages"]
    for key, entry in data["strings"].items():
        if "en" not in entry:
            raise SystemExit(f"{key}: missing English text")
        placeholders = len(PLACEHOLDER.findall(entry["en"]))
        for language in languages:
            text = entry.get(language)
            if text is not None and len(PLACEHOLDER.findall(text)) != placeholders:
                raise SystemExit(f"{key} [{language}]: placeholder count differs from English")
    return data


def build_xcstrings(data: dict) -> str:
    strings = {}
    for key, entry in sorted(data["strings"].items()):
        if "ios" not in entry["platforms"]:
            continue
        localizations = {}
        for language in data["languages"]:
            text = entry.get(language)
            if text is None:
                continue
            unit = {"stringUnit": {"state": "translated", "value": swift_text(text)}}
            localizations[language] = unit
            for alias in APPLE_ALIASES.get(language, []):
                localizations[alias] = unit
        strings[key] = {
            "comment": entry.get("comment", ""),
            "extractionState": "manual",
            "localizations": dict(sorted(localizations.items())),
        }
    catalog = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
    return json.dumps(catalog, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def build_android(data: dict) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for language in data["languages"]:
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by scripts/generate-localizations.py from localization/strings.json. Do not edit. -->",
            "<resources>",
        ]
        count = 0
        for key, entry in sorted(data["strings"].items()):
            if "android" not in entry["platforms"]:
                continue
            text = entry.get(language)
            if text is None:
                continue
            lines.append(f'    <string name="{android_name(key)}">{android_text(text)}</string>')
            count += 1
        lines.append("</resources>")
        if count == 0:
            continue
        for qualifier in ANDROID_QUALIFIERS[language]:
            files[ANDROID_RES / qualifier / "openwish_strings.xml"] = "\n".join(lines) + "\n"
    return files


def main() -> int:
    check = "--check" in sys.argv[1:]
    data = load()
    outputs = {XCSTRINGS: build_xcstrings(data), **build_android(data)}
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run python3 scripts/generate-localizations.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
